-- Script de Criação para PostgreSQL / Supabase
-- Tabelas ordenadas para evitar problemas de restrição de chaves estrangeiras (fks)

-- =========================================
-- TABELAS SEM CHAVES ESTRANGEIRAS (PARENTES)
-- =========================================

CREATE TABLE PAIS (
    ID_PAIS INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SIGLA_PAIS VARCHAR(2),
    NOME_PAIS VARCHAR(40)
);

CREATE TABLE SITUACAO (
    ID_SITUACAO NUMERIC(10,0) PRIMARY KEY,
    DESC_SITUACAO VARCHAR(20)
);

CREATE TABLE TIPO_COLABORADOR (
    ID_TIPO_COLABORADOR INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESC_TIPO_COLABORADOR VARCHAR(20)
);

CREATE TABLE FUNCOES (
    ID_FUNCAO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRICAO_FUNCAO VARCHAR(20),
    ORDEM_FUNCAO INTEGER,
    IMAGEM VARCHAR(10)
);

CREATE TABLE TIPO_ATIVIDADE (
    ID_ATIVIDADE INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESC_ATIVIDADE VARCHAR(30)
);

CREATE TABLE FORMA_ATIVIDADE (
    ID_FORMA_ATIVIDADE INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE TREINAMENTO (
    ID_TREINAMENTO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORMA_TREINAMENTO CHAR(1),
    DESC_TREINAMENTO VARCHAR(100),
    OBS_TREINAMENTO VARCHAR(200),
    DATA_INCLUSAO TIMESTAMPTZ,
    DATA_ATUALIZACAO TIMESTAMPTZ,
    COLABORADOR_ATUALIZOU CHAR(10)
);

-- =========================================
-- TABELAS DEPENDENTES (NÍVEL 1)
-- =========================================

CREATE TABLE ESTADO (
    ID_ESTADO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PAIS INTEGER NOT NULL,
    NOME_ESTADO VARCHAR(40),
    SIGLA_ESTADO VARCHAR(5),
    CONSTRAINT fk_estado_pais FOREIGN KEY (ID_PAIS) REFERENCES PAIS(ID_PAIS)
);

CREATE TABLE REGIONAL (
    ID_REGIONAL INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PAIS INTEGER NOT NULL,
    DESC_REGIONAL VARCHAR(20),
    CONSTRAINT fk_regional_pais FOREIGN KEY (ID_PAIS) REFERENCES PAIS(ID_PAIS)
);

-- =========================================
-- TABELAS DEPENDENTES (NÍVEL 2)
-- =========================================

CREATE TABLE REGIONAL_ESTADO (
    ID_PAIS INTEGER NOT NULL,
    ID_ESTADO INTEGER NOT NULL,
    ID_REGIONAL INTEGER NOT NULL,
    PRIMARY KEY (ID_PAIS, ID_ESTADO, ID_REGIONAL),
    CONSTRAINT fk_re_pais FOREIGN KEY (ID_PAIS) REFERENCES PAIS(ID_PAIS),
    CONSTRAINT fk_re_estado FOREIGN KEY (ID_ESTADO) REFERENCES ESTADO(ID_ESTADO),
    CONSTRAINT fk_re_regional FOREIGN KEY (ID_REGIONAL) REFERENCES REGIONAL(ID_REGIONAL)
);

CREATE TABLE ARQUIDIOCESE (
    ID_ARQUIDIOCESE INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ESTADO INTEGER NOT NULL,
    ID_SITUACAO NUMERIC(10,0) NOT NULL,
    NOME_ARQUIDIOCESE VARCHAR(50),
    UF_ARQUIDIOCESE CHAR(2),
    IDENTIFICA_FOTO NUMERIC(10,0),
    CONSTRAINT fk_arqui_estado FOREIGN KEY (ID_ESTADO) REFERENCES ESTADO(ID_ESTADO),
    CONSTRAINT fk_arqui_situacao FOREIGN KEY (ID_SITUACAO) REFERENCES SITUACAO(ID_SITUACAO)
);

-- =========================================
-- TABELAS DEPENDENTES (NÍVEL 3)
-- =========================================

CREATE TABLE HISTORICO_ARQUIDIOCESE (
    ID_HISTORICO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ARQUIDIOCESE INTEGER NOT NULL,
    DT_HISTORICO TIMESTAMPTZ,
    DESCRICAO_HISTORICO VARCHAR(250),
    CONSTRAINT fk_hist_arqui FOREIGN KEY (ID_ARQUIDIOCESE) REFERENCES ARQUIDIOCESE(ID_ARQUIDIOCESE)
);

CREATE TABLE PAROQUIA (
    ID_PAROQUIA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_REGIONAL INTEGER NOT NULL,
    ID_ARQUIDIOCESE INTEGER NOT NULL,
    ID_ESTADO INTEGER,
    ID_COORDENADOR INTEGER,
    NOME_PAROQUIA VARCHAR(50),
    PAROCO_PAROQUIA VARCHAR(50),
    ENDERECO_PAROQUIA VARCHAR(50),
    BAIRRO_PAROQUIA VARCHAR(30),
    CIDADE_PAROQUIA VARCHAR(40),
    GPS_LATITUDE DOUBLE PRECISION,
    GPS_LONGITUDE DOUBLE PRECISION,
    TIPO_PAROQUIA INTEGER,
    FOTO_PAROQUIA BOOLEAN,
    CONSTRAINT fk_paro_regional FOREIGN KEY (ID_REGIONAL) REFERENCES REGIONAL(ID_REGIONAL),
    CONSTRAINT fk_paro_arqui FOREIGN KEY (ID_ARQUIDIOCESE) REFERENCES ARQUIDIOCESE(ID_ARQUIDIOCESE),
    CONSTRAINT fk_paro_estado FOREIGN KEY (ID_ESTADO) REFERENCES ESTADO(ID_ESTADO)
);

-- =========================================
-- TABELAS DEPENDENTES (NÍVEL 4)
-- =========================================

CREATE TABLE COLABORADOR (
    ID_COLABORADOR INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PAROQUIA INTEGER NOT NULL,
    ID_TIPO_COLABORADOR INTEGER,
    NOME_COLABORADOR VARCHAR(50),
    APELIDO_COLABORADOR VARCHAR(15),
    SEXO CHAR(1),
    DT_NASC_COLABORADOR TIMESTAMPTZ,
    TEL_COLABORADOR VARCHAR(15),
    EMAIL_COLABORADOR VARCHAR(50),
    STATUS_COLABORADOR CHAR(1),
    SENHA_COLABORADOR VARCHAR(40),
    CPF_COLABORADOR NUMERIC(11,0),
    TALENTO_COLABORADOR VARCHAR(1000),
    FOTO_COLABORADOR BYTEA,
    DATA_ATUALIZACAO TIMESTAMPTZ,
    CONSTRAINT fk_colab_paroquia FOREIGN KEY (ID_PAROQUIA) REFERENCES PAROQUIA(ID_PAROQUIA),
    CONSTRAINT fk_colab_tipo FOREIGN KEY (ID_TIPO_COLABORADOR) REFERENCES TIPO_COLABORADOR(ID_TIPO_COLABORADOR)
);

-- =========================================
-- TABELAS DE LIGAÇÃO E DEPENDENTES DE COLABORADOR
-- =========================================

CREATE TABLE ACESSOS_COLABORADOR (
    ID_COLABORADOR INTEGER NOT NULL,
    ID_FUNCAO INTEGER NOT NULL,
    TIPO_ACESSO CHAR(2),
    PRIMARY KEY (ID_COLABORADOR, ID_FUNCAO),
    CONSTRAINT fk_acesso_colab FOREIGN KEY (ID_COLABORADOR) REFERENCES COLABORADOR(ID_COLABORADOR),
    CONSTRAINT fk_acesso_funcao FOREIGN KEY (ID_FUNCAO) REFERENCES FUNCOES(ID_FUNCAO)
);

CREATE TABLE TREINAMENTO_COLABORADOR (
    ID_COLABORADOR INTEGER NOT NULL,
    ID_TREINAMENTO INTEGER NOT NULL,
    STATUS_TREINAMENTO CHAR(1),
    PRIMARY KEY (ID_COLABORADOR, ID_TREINAMENTO),
    CONSTRAINT fk_tc_colab FOREIGN KEY (ID_COLABORADOR) REFERENCES COLABORADOR(ID_COLABORADOR),
    CONSTRAINT fk_tc_treina FOREIGN KEY (ID_TREINAMENTO) REFERENCES TREINAMENTO(ID_TREINAMENTO)
);

CREATE TABLE DIAS_TREINAMENTO (
    ID_TREINAMENTO INTEGER NOT NULL,
    ID_COLABORADOR INTEGER,
    DT_TREINAMENTO DATE,
    HORA_INICIO TIMESTAMPTZ,
    HORA_FIM TIMESTAMPTZ,
    PRIMARY KEY (ID_TREINAMENTO, DT_TREINAMENTO),
    CONSTRAINT fk_dt_treina FOREIGN KEY (ID_TREINAMENTO) REFERENCES TREINAMENTO(ID_TREINAMENTO),
    CONSTRAINT fk_dt_colab FOREIGN KEY (ID_COLABORADOR) REFERENCES COLABORADOR(ID_COLABORADOR)
);
